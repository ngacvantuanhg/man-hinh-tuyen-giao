window.TINH_THEM = function (v) {
  const co = m => typeof v[m] === "number" && !isNaN(v[m]);
  if (co("kg_giai_tt") || co("kg_giai_cn")) v.kg_giai = (v.kg_giai_tt || 0) + (v.kg_giai_cn || 0);
  if (co("kg_dung15") && co("kg_luotthi") && v.kg_luotthi > 0) v.kg_tl15 = v.kg_dung15 / v.kg_luotthi * 100;
  const dt = ["kg_dt_vc","kg_dt_cbcc","kg_dt_hssv","kg_dt_nd","kg_dt_llvt","kg_dt_ldtd","kg_dt_ht","kg_dt_dn"];
  const tong = dt.reduce((s, m) => s + (co(m) ? v[m] : 0), 0);
  if (co("kg_nguoithi") && tong > 0 && v.kg_nguoithi - tong > 0) v.kg_dt_khac = v.kg_nguoithi - tong;
  return v;
};
